  from e join public.crew_members c
    on regexp_replace(c.full_name, '\s', '', 'g') = regexp_replace(e.name, '\s', '', 'g')
on conflict (crew_member_id, entry_date)
do update set code = excluded.code, kind = excluded.kind, ac_type = excluded.ac_type, updated_at = now();

